class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("geo_edu_lang") || "vi";
    if (!I18N_LANGUAGES[this.currentLang]) {
      this.currentLang = "vi";
    }
    // Auto-translate is enabled by default for all system content
    const savedAutoTranslate = localStorage.getItem("geo_edu_auto_translate");
    this.autoTranslateEnabled = savedAutoTranslate !== null ? savedAutoTranslate === "true" : true;
  }

  getLang() {
    return this.currentLang;
  }

  getLanguageMeta(langCode = this.currentLang) {
    return I18N_LANGUAGES[langCode] || I18N_LANGUAGES.vi;
  }

  t(key, fallback = "") {
    const langDict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.vi;
    if (langDict && langDict[key] !== undefined) {
      return langDict[key];
    }
    if (TRANSLATIONS.vi && TRANSLATIONS.vi[key] !== undefined) {
      return TRANSLATIONS.vi[key];
    }
    return fallback || key;
  }

  toggleAutoTranslate() {
    this.autoTranslateEnabled = !this.autoTranslateEnabled;
    localStorage.setItem("geo_edu_auto_translate", this.autoTranslateEnabled);
    if (window.appState && typeof switchTab === "function") {
      switchTab(window.appState.currentTab);
    }
    return this.autoTranslateEnabled;
  }

  hasDocTranslation(docId, lang = this.currentLang) {
    return Boolean(DOCS_I18N[docId] && DOCS_I18N[docId][lang]);
  }

  hasPostTranslation(postId, lang = this.currentLang) {
    return Boolean(POSTS_I18N[postId] && POSTS_I18N[postId][lang]);
  }

  isManualDoc(doc) {
    if (!doc) return false;
    if (doc.isManual) return true;
    if (DOCS_I18N[doc.id]) return false;
    return Boolean(doc.id && !doc.id.startsWith("doc-dc-") && !doc.id.startsWith("doc-vn-"));
  }

  isManualPost(post) {
    if (!post) return false;
    if (post.isManual) return true;
    if (POSTS_I18N[post.id]) return false;
    return Boolean(post.id && post.id !== "hshk-1" && post.id !== "hshk-2" && post.id !== "grp-1" && post.id !== "grp-2" && post.id !== "group-1");
  }

  // Get translated document attributes based on active language or forced flag
  // Automatically translates system documents, while PRESERVING author original text for manual uploads
  getDocumentData(doc, forceLang = null) {
    if (!doc) return { title: "", desc: "", previewText: "" };
    const lang = forceLang || this.currentLang;
    // Manual uploads are strictly kept in original language
    if (this.isManualDoc(doc)) {
      return {
        title: doc.title || "",
        desc: doc.desc || "",
        previewText: doc.previewText || doc.desc || ""
      };
    }
    if (lang === "vi" || !DOCS_I18N[doc.id] || !DOCS_I18N[doc.id][lang]) {
      return {
        title: doc.title || "",
        desc: doc.desc || "",
        previewText: doc.previewText || doc.desc || ""
      };
    }
    const tDoc = DOCS_I18N[doc.id][lang];
    return {
      title: tDoc.title || doc.title,
      desc: tDoc.desc || doc.desc,
      previewText: tDoc.previewText || doc.previewText || doc.desc || ""
    };
  }

  // Get translated post attributes based on active language or forced flag
  // Automatically translates system posts, while PRESERVING author original text for manual posts
  getPostData(post, forceLang = null) {
    if (!post) return { title: "", tag: "", content: "" };
    const lang = forceLang || this.currentLang;
    // Manual posts are strictly kept in original language
    if (this.isManualPost(post)) {
      return {
        title: post.title || "",
        tag: post.tag || "",
        content: post.content || ""
      };
    }
    if (lang === "vi" || !POSTS_I18N[post.id] || !POSTS_I18N[post.id][lang]) {
      return {
        title: post.title || "",
        tag: post.tag || "",
        content: post.content || ""
      };
    }
    const tPost = POSTS_I18N[post.id][lang];
    return {
      title: tPost.title || post.title,
      tag: tPost.tag || post.tag,
      content: tPost.content || post.content
    };
  }

  setLanguage(langCode) {
    if (!I18N_LANGUAGES[langCode]) return;
    this.currentLang = langCode;
    localStorage.setItem("geo_edu_lang", langCode);
    document.documentElement.lang = langCode;

    // Apply translations across DOM
    this.applyTranslations();

    // Trigger re-render of current view in app.js
    if (window.appState && typeof switchTab === "function") {
      switchTab(window.appState.currentTab);
    }
    if (typeof renderAiWelcome === "function") {
      renderAiWelcome();
    }
  }

  applyTranslations() {
    // 1. Elements with data-i18n (Text Content)
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (key) {
        el.textContent = this.t(key, el.textContent);
      }
    });

    // 2. Elements with data-i18n-html (HTML Content)
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
      const key = el.getAttribute("data-i18n-html");
      if (key) {
        el.innerHTML = this.t(key, el.innerHTML);
      }
    });

    // 3. Elements with data-i18n-placeholder
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) {
        el.placeholder = this.t(key, el.placeholder);
      }
    });

    // 4. Elements with data-i18n-title
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
      const key = el.getAttribute("data-i18n-title");
      if (key) {
        el.title = this.t(key, el.title);
      }
    });

    // 5. Update Language Selector Button Display
    const currentMeta = this.getLanguageMeta();
    const langBtnFlag = document.getElementById("current-lang-flag");
    const langBtnName = document.getElementById("current-lang-name");
    if (langBtnFlag) langBtnFlag.textContent = currentMeta.flag;
    if (langBtnName) langBtnName.textContent = currentMeta.name;

    // Update active class in dropdown
    document.querySelectorAll(".lang-option-item").forEach(item => {
      const lang = item.getAttribute("data-lang");
      if (lang === this.currentLang) {
        item.classList.add("active");
      } else {
        item.classList.remove("active");
      }
    });
  }
}

// Instantiate global i18n manager
window.geoI18n = new I18nManager();
window.t = (key, fallback) => window.geoI18n.t(key, fallback);
