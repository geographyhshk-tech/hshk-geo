function getCountryName(code, lang) {
  const country = GLOBE_COUNTRY_DATA[code];
  if (!country) return code;
  return country.name[lang] || country.name.en || code;
}

function getCountryPopulation(code, year) {
  const country = GLOBE_COUNTRY_DATA[code];
  if (!country || !country.population) return 0;
  if (country.population[year] !== undefined) return country.population[year];
  const years = Object.keys(country.population).map(Number).sort();
  if (year < years[0]) return country.population[years[0]];
  if (year > years[years.length - 1]) return country.population[years[years.length - 1]];
  let lo = years[0], hi = years[years.length - 1];
  for (let i = 0; i < years.length - 1; i++) {
    if (years[i] <= year && year <= years[i + 1]) { lo = years[i]; hi = years[i + 1]; break; }
  }
  const pLo = country.population[lo], pHi = country.population[hi];
  return Math.round(pLo + (pHi - pLo) * (year - lo) / (hi - lo));
}

function getCountryGDP(code, year) {
  const country = GLOBE_COUNTRY_DATA[code];
  if (!country || !country.gdp) return 0;
  if (country.gdp[year] !== undefined) return country.gdp[year];
  const years = Object.keys(country.gdp).map(Number).sort();
  if (year < years[0]) return country.gdp[years[0]];
  if (year > years[years.length - 1]) return country.gdp[years[years.length - 1]];
  let lo = years[0], hi = years[years.length - 1];
  for (let i = 0; i < years.length - 1; i++) {
    if (years[i] <= year && year <= years[i + 1]) { lo = years[i]; hi = years[i + 1]; break; }
  }
  const gLo = country.gdp[lo], gHi = country.gdp[hi];
  return Math.round((gLo + (gHi - gLo) * (year - lo) / (hi - lo)) * 100) / 100;
}

function formatPopulation(num, lang) {
  if (!num) return "N/A";
  if (num >= 1e9) return (num / 1e9).toFixed(2) + (lang === "vi" ? " tỷ" : " B");
  if (num >= 1e6) return (num / 1e6).toFixed(2) + (lang === "vi" ? " triệu" : " M");
  return num.toLocaleString();
}

function getCountryByIso2(iso2) {
  for (const code in GLOBE_COUNTRY_DATA) {
    if (GLOBE_COUNTRY_DATA[code].iso2 === iso2.toLowerCase()) return GLOBE_COUNTRY_DATA[code];
  }
  return null;
}

